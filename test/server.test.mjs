import test from 'node:test';
import http from 'node:http';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { QuotaForge } from '../src/service.mjs';
import { startServer } from '../src/server.mjs';
test('loopback API requires same origin and session token; local demo is end-to-end', async (t) => {
  const parent = path.resolve(tmpdir());
  const directory = await mkdtemp(path.join(parent, 'quotaforge-http-'));
  const service = new QuotaForge({ dataDir: directory, detect: async () => [] });
  const server = await startServer({ port: 0, service });
  t.after(async () => {
    server.closeAllConnections();
    await new Promise((resolve) => server.close(resolve));
    assert.equal(path.dirname(path.resolve(directory)), parent);
    await rm(directory, { recursive: true, force: true });
  });
  const base = 'http://127.0.0.1:' + server.address().port;
  const initial = await (await fetch(base + '/api/state')).json();
  assert.equal(initial.summary.cashReceivedUsd, 0);
  assert.equal(typeof initial.csrfToken, 'string');
  const post = (route, body, headers = {}) => fetch(base + route, { method: 'POST', headers: { 'Content-Type': 'application/json', ...headers }, body: JSON.stringify(body) });
  assert.equal((await post('/api/demo', {})).status, 403);
  assert.equal((await post('/api/demo', {}, { 'X-QF-Token': initial.csrfToken, Origin: 'https://attacker.invalid' })).status, 403);
  const forgedHostStatus = await new Promise((resolve, reject) => { const req = http.get(base + '/api/state', { headers: { Host: 'attacker.invalid' } }, (res) => { res.resume(); resolve(res.statusCode); }); req.on('error', reject); });
  assert.equal(forgedHostStatus, 403);
  const response = await post('/api/demo', {}, { 'X-QF-Token': initial.csrfToken });
  assert.equal(response.status, 201);
  const project = await response.json();
  assert.equal(project.verification.passed, true);
  assert.equal(project.generation.deterministic, true);
  const artifact = await (await fetch(base + '/api/projects/' + project.id + '/artifact')).json();
  assert.equal(artifact.artifactHash, project.verification.artifactHash);
  const state = await (await fetch(base + '/api/state')).json();
  assert.equal(state.ledger.length, 0);
  assert.equal(state.projects.length, 1);
  assert.equal((await fetch(base + '/.quotaforge/state.json')).status, 404);
});
